from ultralytics import YOLO
import cv2
import easyocr
import pandas as pd
from datetime import datetime

vehicle_model = YOLO("yolov8n.pt")

reader = easyocr.Reader(['en'])


video_path = "videos/uploaded_video.mp4"

cap = cv2.VideoCapture(video_path)

width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
fps = int(cap.get(cv2.CAP_PROP_FPS))

out = cv2.VideoWriter(
    "outputs/final_output.mp4",
    cv2.VideoWriter_fourcc(*'mp4v'),
    fps,
    (width, height)
)

LINE_Y = 400

vehicle_positions = {}

vehicle_paths  = {}

previous_centers={}

crossed_ids = set()

records = []

while True:

    ret, frame = cap.read()

    if not ret:
        break

    # TRACK VEHICLES
    results = vehicle_model.track(
        frame,
        persist=True,
        tracker="bytetrack.yaml"
    )

    annotated_frame = results[0].plot()

    cv2.line(
        annotated_frame,
        (0, LINE_Y),
        (width, LINE_Y),
        (0, 255, 0),
        3
    )

    if results[0].boxes.id is not None:

        boxes = results[0].boxes.xyxy.cpu().numpy()
        ids = results[0].boxes.id.cpu().numpy()

        classes = results[0].boxes.cls.cpu().numpy()
        class_names = vehicle_model.names


        for i, (box, track_id) in enumerate(zip(boxes, ids)):

            x1,y1,x2,y2 = map(int, box)

            cls_id = int(classes[i])
            vehicle_type = class_names[cls_id]

            center_x=int((x1 + x2) / 2)
            center_y=int((y1 + y2) / 2)

            speed=0

            previous_y=vehicle_positions.get(track_id, center_y)

           
            vehicle_positions[track_id] = center_y

            if track_id in previous_centers:
                prev_center_x, prev_center_y = previous_centers[track_id]

                dx=center_x - prev_center_x
                dy=center_y - prev_center_y

                distance=(dx**2 + dy**2)**0.5

                speed=distance * fps * 0.1

            previous_centers[track_id]=(center_x, center_y)

            if track_id not in vehicle_paths:
                vehicle_paths[track_id] = []

            vehicle_paths[track_id].append((center_x, center_y))

            for j in range(1, len(vehicle_paths[track_id])):

                cv2.line(
                    annotated_frame,
                    vehicle_paths[track_id][j - 1],
                    vehicle_paths[track_id][j],
                    (255, 0, 0),
                    2
                        )
        
            cv2.putText(
                        annotated_frame,
                        f"{int(speed)} km/h",
                        (x1, y1 - 10),
                        cv2.FONT_HERSHEY_SIMPLEX,
                        0.6,
                        (0, 255, 255),
                        2
                        )
                
            if previous_y < LINE_Y and center_y >= LINE_Y:

                if track_id not in crossed_ids:

                    crossed_ids.add(track_id)

                    vehicle_crop = frame[y1:y2, x1:x2]
                    h, w, _ = vehicle_crop.shape
                    lower_half = vehicle_crop[h//2:h, :]
                    ocr_result = reader.readtext(lower_half)
                    plate_text = "UNKNOWN"

                    if len(ocr_result) > 0:

                        # Take longest detected text
                        texts = [r[1] for r in ocr_result]
                        plate_text = max(texts, key=len)


                    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                    print(f"Vehicle {track_id} | Plate: {plate_text} | Time: {timestamp}")

                    records.append({
                        "Vehicle_ID": int(track_id),
                        "Vehicle_Type": vehicle_type,
                        "Speed": int(speed),
                        "Plate_Number": plate_text,
                        "Timestamp": timestamp
                    })

    out.write(annotated_frame)

cap.release()
out.release()


df = pd.DataFrame(records)
df.to_csv("outputs/vehicle_records.csv", index=False)
print("FINAL PROCESS COMPLETE")


